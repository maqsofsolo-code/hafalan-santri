-- Master segmen ujian Hafalan Digital.
-- Batas halaman mengikuti standard1-quran.pdf (Mushaf Madinah 604 halaman).
-- Arah urutan: An-Nas menuju Al-Baqarah; halaman 1 (Al-Fatihah) tidak termasuk.
CREATE TABLE IF NOT EXISTS public.master_segment_ujian (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  juz integer NOT NULL,
  segmen integer NOT NULL,
  urutan_global integer NOT NULL,
  halaman_awal integer NOT NULL,
  halaman_akhir integer NOT NULL,
  jumlah_halaman integer NOT NULL,
  surah_awal_nomor integer NOT NULL REFERENCES public.surah(nomor) ON DELETE RESTRICT,
  ayat_awal integer NOT NULL,
  surah_akhir_nomor integer NOT NULL REFERENCES public.surah(nomor) ON DELETE RESTRICT,
  ayat_akhir integer NOT NULL,
  is_aktif boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT master_segment_ujian_juz_check CHECK (juz BETWEEN 1 AND 30),
  CONSTRAINT master_segment_ujian_segmen_check CHECK (
    (juz BETWEEN 1 AND 29 AND segmen BETWEEN 1 AND 5)
    OR (juz = 30 AND segmen BETWEEN 1 AND 6)
  ),
  CONSTRAINT master_segment_ujian_juz_segmen_key UNIQUE (juz, segmen),
  CONSTRAINT master_segment_ujian_urutan_global_key UNIQUE (urutan_global),
  CONSTRAINT master_segment_ujian_urutan_global_check CHECK (urutan_global BETWEEN 1 AND 151),
  CONSTRAINT master_segment_ujian_halaman_awal_check CHECK (halaman_awal BETWEEN 1 AND 604),
  CONSTRAINT master_segment_ujian_halaman_akhir_check CHECK (halaman_akhir BETWEEN 1 AND 604),
  CONSTRAINT master_segment_ujian_jumlah_halaman_check CHECK (jumlah_halaman IN (3, 4)),
  CONSTRAINT master_segment_ujian_rentang_halaman_check CHECK (
    halaman_awal >= halaman_akhir
    AND jumlah_halaman = halaman_awal - halaman_akhir + 1
  ),
  CONSTRAINT master_segment_ujian_surah_awal_check CHECK (surah_awal_nomor BETWEEN 1 AND 114),
  CONSTRAINT master_segment_ujian_surah_akhir_check CHECK (surah_akhir_nomor BETWEEN 1 AND 114),
  CONSTRAINT master_segment_ujian_ayat_awal_check CHECK (ayat_awal > 0),
  CONSTRAINT master_segment_ujian_ayat_akhir_check CHECK (ayat_akhir > 0)
);

CREATE OR REPLACE FUNCTION public.validate_master_segment_ujian_ayat()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  jumlah_ayat_awal integer;
  jumlah_ayat_akhir integer;
BEGIN
  SELECT jumlah_ayat INTO jumlah_ayat_awal
  FROM public.surah
  WHERE nomor = NEW.surah_awal_nomor;

  SELECT jumlah_ayat INTO jumlah_ayat_akhir
  FROM public.surah
  WHERE nomor = NEW.surah_akhir_nomor;

  IF jumlah_ayat_awal IS NULL OR NEW.ayat_awal > jumlah_ayat_awal THEN
    RAISE EXCEPTION 'Ayat awal master segmen tidak valid';
  END IF;

  IF jumlah_ayat_akhir IS NULL OR NEW.ayat_akhir > jumlah_ayat_akhir THEN
    RAISE EXCEPTION 'Ayat akhir master segmen tidak valid';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS validate_master_segment_ujian_ayat_trigger
  ON public.master_segment_ujian;
CREATE TRIGGER validate_master_segment_ujian_ayat_trigger
BEFORE INSERT OR UPDATE OF surah_awal_nomor, ayat_awal, surah_akhir_nomor, ayat_akhir
ON public.master_segment_ujian
FOR EACH ROW
EXECUTE FUNCTION public.validate_master_segment_ujian_ayat();

